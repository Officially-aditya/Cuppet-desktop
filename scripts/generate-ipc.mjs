import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { IPC_METHODS, IPC_EVENTS, IPC_ARGUMENT_TYPES } from '../src/shared/ipc-contract.mjs';

const header = '// Generated by scripts/generate-ipc.mjs from src/shared/ipc-contract.mjs.\n';
const methods = Object.entries(IPC_METHODS).map(([name, spec]) => [name, spec.channel]);
const events = Object.entries(IPC_EVENTS).map(([name, spec]) => [name, spec.channel]);
const preload = header + `const { contextBridge, ipcRenderer } = require('electron');

const bridge = {};
function expose(path, value) {
  const keys = path.split('.');
  const leaf = keys.pop();
  let target = bridge;
  for (const key of keys) target = target[key] ??= {};
  target[leaf] = value;
}
for (const [path, channel] of ${JSON.stringify(methods, null, 2)}) {
  expose(path, (...args) => ipcRenderer.invoke(channel, ...args));
}
for (const [path, channel] of ${JSON.stringify(events, null, 2)}) {
  expose(path, (callback) => {
    if (typeof callback !== 'function') return () => {};
    const listener = (_event, payload) => callback(payload);
    ipcRenderer.on(channel, listener);
    return () => ipcRenderer.removeListener(channel, listener);
  });
}
expose('native.platform', process.platform);
contextBridge.exposeInMainWorld('cuppet', bridge);
`;

const tree = {};
function typeAt(path, value) {
  const keys = path.split('.');
  const leaf = keys.pop();
  let target = tree;
  for (const key of keys) target = target[key] ??= {};
  target[leaf] = value;
}
for (const [name, spec] of Object.entries(IPC_METHODS)) {
  const args = spec.args.map(([parameter, kind]) => `${parameter}: ${IPC_ARGUMENT_TYPES[kind]}`).join(', ');
  typeAt(name, `(${args}) => Promise<${spec.result}>`);
}
for (const [name, spec] of Object.entries(IPC_EVENTS)) typeAt(name, `(callback: (event: ${spec.type}) => void) => () => void`);
typeAt('native.platform', 'string');
function printTree(value, depth = 0) {
  return '{\n' + Object.entries(value).map(([key, item]) => '  '.repeat(depth + 1) + key + ': ' + (typeof item === 'string' ? item : printTree(item, depth + 1)) + ';').join('\n') + '\n' + '  '.repeat(depth) + '}';
}
const types = header + "import type * as Types from './types';\n\nexport type CuppetApi = " + printTree(tree) + ';\n';
for (const [path, content] of [['src/preload/preload.cjs', preload], ['src/renderer/ipc-api.d.ts', types]]) {
  const url = new URL('../' + path, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error('Regenerate IPC contract: ' + fileURLToPath(url));
  } else {
    await writeFile(url, content);
  }
}
